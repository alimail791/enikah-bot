import pg from 'pg';

export const pool = new pg.Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.PGSSL === '1' ? { rejectUnauthorized: false } : false,
});

export const q = (t, p) => pool.query(t, p);
export const one = async (t, p) => (await pool.query(t, p)).rows[0];
export const all = async (t, p) => (await pool.query(t, p)).rows;

const SCHEMA = `
create table if not exists users(
  phone text primary key,
  type text,                         -- null | person | broker | admin (website accounts)
  name text, city text,
  status text default 'unverified',  -- broker ID verification
  exp timestamptz,                   -- broker plan end
  pid int,                           -- person's own profile
  last_in timestamptz,               -- last inbound message (24h window)
  rem3 timestamptz, rem0 timestamptz,
  created timestamptz default now());

create table if not exists profiles(
  id int generated by default as identity (start with 1001) primary key,
  owner text, broker text,
  name text, g text, age int, city text, maslak text, marital text, edu text, job text,
  pa_min int, pa_max int, pm text default 'any',
  status text default 'unverified',  -- unverified | pending | verified | blocked
  exp timestamptz,                   -- own plan end (null for broker candidates)
  photo bytea, photo_mime text,
  rem3 timestamptz, rem0 timestamptz,
  created timestamptz default now());

create table if not exists sessions(phone text primary key, data jsonb);

create table if not exists seen(
  pid int, sid int, period timestamptz, at timestamptz default now(),
  primary key(pid, sid));

create table if not exists interests(
  id serial primary key, from_id int, to_id int, st text default 'sent',
  created timestamptz default now(), unique(from_id, to_id));

create table if not exists tokens(
  token text primary key, kind text, phone text, ref text, data jsonb, expires timestamptz);

create table if not exists docs(
  id serial primary key, kind text, ref text, phone text,
  id_doc bytea, id_mime text, photo bytea, photo_mime text,
  created timestamptz default now());

create table if not exists payments(
  id serial primary key, phone text, kind text, amount int, link_id text unique,
  status text default 'created', created timestamptz default now(), paid_at timestamptz);

create table if not exists notes(
  id serial primary key, phone text, text text, link text, seen boolean default false,
  created timestamptz default now());
create index if not exists notes_phone on notes(phone, id desc);

alter table users add column if not exists pw text;
alter table users add column if not exists email text;

alter table users add column if not exists email_ok boolean default false;
alter table users add column if not exists phone_ok boolean default false;
alter table users add column if not exists source text;
alter table users add column if not exists lang text;
alter table payments add column if not exists method text default 'razorpay';
alter table payments add column if not exists utr text;

create table if not exists visits(
  id serial primary key, vid text, source text, landing text, device text, created timestamptz default now());
create index if not exists visits_created on visits(created);

create table if not exists followups(phone text, step text, sent timestamptz default now(), primary key(phone, step));
create table if not exists settings(key text primary key, value text);

create table if not exists partners(
  id serial primary key, slug text unique, token text unique, name text, kind text, city text, phone text, created timestamptz default now());

create table if not exists reports(
  id serial primary key, phone text, pid int, reason text, created timestamptz default now());
`;

export const migrate = () => q(SCHEMA);

// A profile with its effective plan end (own or broker's) and whether it is live.
export const P_SQL = `select p.*, 'ENK'||p.id as code,
  case when p.broker is not null then b.exp else p.exp end as till,
  coalesce(case when p.broker is not null then b.exp > now() and b.status = 'verified' else p.exp > now() end, false) as live
  from profiles p left join users b on b.phone = p.broker`;

export const getP = id => one(P_SQL + ' where p.id = $1', [id]);
export const visible = p => !!p && p.live && p.status === 'verified';
